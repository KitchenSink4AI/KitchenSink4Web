PROBE = """
(() => ({
  nodes: document.getElementsByTagName('*').length,
  title: document.title,
  controls: document.querySelectorAll(
    'input, select, textarea, button, [role=button], [role=switch]').length,
  links: document.querySelectorAll('a[href]').length,
  iframes: document.querySelectorAll('iframe').length,
  tables: document.querySelectorAll('table').length,
  role_tables: document.querySelectorAll('[role=table], [role=grid]').length,
  images: document.querySelectorAll('img').length,
  text_chars: (document.body ? (document.body.innerText || '') : '').length,
  truth: window.__truth || null,
}))()
"""


class _Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *args):  # noqa: D102, ANN002
        pass


def _serve(directory: Path) -> tuple[int, socketserver.TCPServer]:
    handler = functools.partial(_Quiet, directory=str(directory))
    httpd = socketserver.TCPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    return httpd.server_address[1], httpd


def _kst() -> str:
    out = subprocess.run(["date", "+%Y-%m-%d %H:%M"], capture_output=True,
                         text=True, shell=False)
    return out.stdout.strip() if out.returncode == 0 else ""


async def _load(page, url: str) -> dict:
    errors: list[str] = []
    console: list[str] = []

    def on_console(msg):
        if msg.type == "error":
            console.append(msg.text[:160])

    def on_pageerror(exc):
        errors.append(str(exc)[:200])

    page.on("console", on_console)
    page.on("pageerror", on_pageerror)
    try:
        await page.goto(url, wait_until="load", timeout=90000)
        # Give React roots, shadow attachment, and the observers a turn.
        await page.wait_for_timeout(600)
        info = await page.evaluate(PROBE)
    finally:
        page.remove_listener("console", on_console)
        page.remove_listener("pageerror", on_pageerror)
    info["page_errors"] = errors
    # Cap the console list. console_flood.html would otherwise put its whole
    # flood in the report, which is the failure the page exists to provoke.
    info["console_errors"] = console[:5]
    info["console_error_count"] = len(console)
    return info


async def main() -> None:
    port, httpd = _serve(HERE)
    session = await MANAGER.open(lane="A", engine="chromium", headless=True)
    rows: dict[str, dict] = {}
    failed: list[str] = []
    try:
        record = session.page(session.focused)
        page = record.page
        for name in PAGES:
            if not (HERE / name).exists():
                print(f"{name:>22}: MISSING")
                failed.append(name)
                continue
            try:
                info = await _load(page, f"http://127.0.0.1:{port}/{name}")
            except Exception as exc:  # noqa: BLE001
                print(f"{name:>22}: LOAD FAILED {exc.__class__.__name__}")
                failed.append(name)
                continue
            rows[name] = info
            flag = ""
            if info["page_errors"]:
                flag = f"  PAGE ERROR: {info['page_errors'][0]}"
                failed.append(name)
            elif info["console_error_count"]:
                flag = f"  ({info['console_error_count']} console errors)"
            print(f"{name:>22}: {info['nodes']:>6} nodes, "
                  f"{info['controls']:>4} controls, "
                  f"{info['links']:>4} links, "
                  f"{info['iframes']} iframes{flag}")
    finally:
        await MANAGER.close(session.session_id)
        httpd.shutdown()

    if "--manifest" in sys.argv:
        manifest = {
            "corpus": "B",
            "purpose": "the pathological fixture site (PLAN 1.3): every "
                       "landmine, deliberately, served from the repo",
            "measured_kst": _kst(),
            "lane": "A(chromium) headless, served from 127.0.0.1",
            "network": "none required. The two https://example.com iframes "
                       "are expected to fail offline; the iframe ELEMENT is "
                       "the fixture, not its content.",
            "generated_files": {
                "dom50k.html": "corpus/b/_generate.py. The generator writes "
                               "the file and the FILE is committed, so the "
                               "node count is a property of the bytes on "
                               "disk rather than of how fast the machine "
                               "ran. No inline script builds nodes.",
                "bigform.html": "corpus/b/_generate.py, same reason: 320 "
                                "controls are not reviewable by hand and a "
                                "hand-maintained file that size drifts.",
            },
            "copied_from_spikes": {
                "app.html": "spikes/s2/fixtures/app.html",
                "other.html": "spikes/s2/fixtures/other.html",
                "virtual.html": "spikes/s2/fixtures/virtual.html",
                "vendor/": "spikes/s2/fixtures/vendor/ (React 18.3.1 and "
                           "react-window 1.8.10 as UMD builds, so there is "
                           "no build step and no network at run time)",
                "note": "COPIED, not moved. PLAN 1.3 says the S2 subset "
                        "moves into corpus B proper before Phase 2 closes; "
                        "spikes/s2 is left intact so the spike record still "
                        "runs.",
            },
            "pages": {},
        }
        for name, (what, mines) in PAGES.items():
            row = rows.get(name)
            path = HERE / name
            entry = {
                "what": what,
                "landmines": mines,
                "loaded": row is not None and not row["page_errors"],
            }
            if path.exists():
                data = path.read_bytes()
                entry["bytes"] = len(data)
                entry["sha256"] = hashlib.sha256(data).hexdigest()
            if row:
                entry.update({
                    "nodes": row["nodes"],
                    "title": row["title"],
                    "controls": row["controls"],
                    "links": row["links"],
                    "iframes": row["iframes"],
                    "tables": row["tables"],
                    "role_tables": row["role_tables"],
                    "images": row["images"],
                    "text_chars": row["text_chars"],
                    "page_errors": row["page_errors"],
                    "console_error_count": row["console_error_count"],
                    "console_errors_sample": row["console_errors"],
                })
                if row["truth"]:
                    entry["ground_truth_window___truth"] = row["truth"]
            manifest["pages"][name] = entry
        index: dict[str, list[str]] = {}
        for name, (_what, mines) in PAGES.items():
            for mine in mines:
                index.setdefault(mine, []).append(name)
        manifest["landmine_index"] = {k: index[k] for k in sorted(index)}
        (HERE / "MANIFEST.json").write_text(
            json.dumps(manifest, indent=1, sort_keys=True), encoding="utf-8")
        print(f"\nwrote {HERE / 'MANIFEST.json'}")

    if failed:
        print(f"\nFAILED: {failed}")
        sys.exit(1)
    print(f"\nall {len(rows)} pages loaded, no page errors")


if __name__ == "__main__":
    asyncio.run(main())
