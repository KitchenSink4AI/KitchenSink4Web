"""Load every corpus B page and report what the browser actually found.

A fixture corpus rots quietly. A vendored UMD build gets moved, a script
throws on line one and the page still returns 200, a generated file goes
stale against its generator, and the page keeps "passing" because nothing
ever asserted that it loads. This script is the assertion: it serves
`corpus/b/` over localhost with the bundled Chromium, opens every page, and
prints the node count, the control count, and every console error and page
error raised during load.

It also writes `MANIFEST.json` when run with `--manifest`, so the node counts
in the manifest are MEASURED rather than estimated. The landmine mapping is
hand-written and lives in this file, because a landmine is a claim about
intent and no script can infer one.

Exit code 0 means every page loaded with no page error. Console errors are
reported but do not fail the run: `console_flood.html` emits two on purpose
and the cross-origin iframes fail to load offline by design.

Run:  .venv/Scripts/python.exe -X utf8 corpus/b/_check.py
      .venv/Scripts/python.exe -X utf8 corpus/b/_check.py --manifest
"""

